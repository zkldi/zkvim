local actions = require("zkvim.actions")
local panels = require("zkvim.panels")
local map = vim.keymap.set
local editor = { "n", "i", "x" }
pcall(vim.keymap.del, "n", "<C-k>")

local function bind(lhs, rhs, desc, modes)
  map(modes or editor, lhs, rhs, { desc = desc, silent = true })
end

bind("<C-s>", actions.save, "Save")
bind("<C-k><C-s>", "<cmd>wall<cr>", "Save all")
bind("<C-k>s", "<cmd>wall<cr>", "Save all")
bind("<C-c>", actions.copy, "Copy selection or line")
bind("<C-x>", actions.cut, "Cut selection or line")
bind("<C-d>", actions.cut, "Cut selection or line")
bind("<C-v>", actions.paste, "Paste")
bind("<C-z>", "<cmd>undo<cr>", "Undo")
bind("<C-S-z>", "<cmd>redo<cr>", "Redo")
bind("<C-y>", "<cmd>redo<cr>", "Redo")
bind("<C-a>", "<Esc>ggVG", "Select all")
bind("<C-l>", "<Esc>^vg_", "Select line")
bind("<C-f>", actions.find, "Find in file")
bind("<C-h>", actions.replace, "Replace in file")
bind("<C-p>", function()
  Snacks.picker.files({ cwd = LazyVim.root() })
end, "Find files")
bind("<C-S-p>", function()
  Snacks.picker.commands()
end, "Command palette")
bind("<C-S-f>", function()
  Snacks.picker.grep({ cwd = LazyVim.root() })
end, "Search project")
bind("<C-r>", function()
  Snacks.picker.projects()
end, "Recent projects")
bind("<C-t>", function()
  Snacks.picker.lsp_workspace_symbols()
end, "Project symbols")
bind("<C-n>", "<cmd>enew<cr>", "New file")
bind("<C-o>", actions.open, "Open file or directory")
bind("<C-w>", actions.close, "Close active file")
bind("<C-S-t>", actions.reopen, "Reopen closed file")
bind("<C-q>", "<cmd>confirm qall<cr>", "Quit")
bind("<C-b>", "<C-o>", "Go back", { "n", "x" })
bind("<C-S-b>", "<C-i>", "Go forward", { "n", "x" })
bind("<C-b>", "<C-o><C-o>", "Go back", "i")
bind("<C-S-b>", "<C-o><C-i>", "Go forward", "i")
bind("<C-2>", actions.activate_second_pane, "Activate second pane")
bind("<C-g>", actions.goto_line, "Go to line")
bind("<C-Enter>", function()
  actions.newline(false)
end, "Newline below")
bind("<C-S-Enter>", function()
  actions.newline(true)
end, "Newline above")
bind("<C-Left>", "<Esc>b", "Previous word")
bind("<C-Right>", "<Esc>e", "Next word")
bind("<C-Left>", "<C-o>b", "Previous word", "i")
bind("<C-Right>", "<C-o>e", "Next word", "i")
bind("<C-BS>", "<C-w>", "Delete previous word", "i")
bind("<C-.>", vim.lsp.buf.code_action, "Code actions")
-- Intentionally invoke Neovim's built-in comment mappings.
for _, mode in ipairs({ "n", "x", "i" }) do
  local rhs = mode == "n" and "gcc" or mode == "x" and "gc" or "<C-o>gcc"
  for _, key in ipairs({ "<C-/>", "<C-_>" }) do
    map(mode, key, rhs, { remap = true, silent = true, desc = "Toggle comment" })
  end
end
bind("<C-j>", panels.terminal, "Toggle bottom dock")
bind("<C-`>", panels.terminal, "Toggle terminal")
bind("<C-S-e>", function()
  panels.show("filesystem")
end, "Toggle project panel")
bind("<C-k>m", function()
  Snacks.zen.zoom()
end, "Zoom pane")
bind("<C-k><C-m>", function()
  Snacks.zen.zoom()
end, "Zoom pane")
map("t", "<C-`>", panels.terminal, { desc = "Toggle terminal" })
-- Keep Ctrl-W and Ctrl-J available to the shell; Escape twice leaves terminal mode.

bind("<leader>zp", function()
  Snacks.picker.commands()
end, "Command palette", "n")
bind("<leader>zf", function()
  Snacks.picker.files({ cwd = LazyVim.root() })
end, "Find files", "n")
bind("<leader>zs", function()
  Snacks.picker.grep({ cwd = LazyVim.root() })
end, "Search project", "n")
bind("<leader>zt", panels.terminal, "Bottom terminal", "n")
bind("<leader>ze", function()
  panels.show("filesystem")
end, "Project panel", "n")
bind("<leader>zo", function()
  panels.show("outline")
end, "Outline panel", "n")
bind("<leader>zg", function()
  panels.show("git_status")
end, "Git panel", "n")
bind("<leader>zr", actions.reopen, "Reopen file", "n")
bind("<leader>zk", actions.check_key, "Check terminal key", "n")
bind("<leader>z?", function()
  Snacks.picker.keymaps()
end, "Search keybindings", "n")

-- Ctrl-W closes files here, so window shortcuts must not remap through it.
for key, direction in pairs({ h = "h", j = "j", k = "k", l = "l", ["="] = "=" }) do
  bind("<leader>w" .. key, "<cmd>wincmd " .. direction .. "<cr>", "Window " .. direction, "n")
end
bind("<leader>wd", "<cmd>close<cr>", "Close pane", "n")
bind("<leader>wv", "<cmd>vsplit<cr>", "Split right", "n")
bind("<leader>ws", "<cmd>split<cr>", "Split below", "n")
bind("<leader>|", "<cmd>vsplit<cr>", "Split right", "n")
bind("<leader>-", "<cmd>split<cr>", "Split below", "n")

-- s is provided by EasyMotion; keep S reserved as in Zed.
map({ "n", "x" }, "S", "<Nop>", { desc = "Reserved" })
